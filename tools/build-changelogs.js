#!/usr/bin/env node
/* Collects every game's own changelog (each game keeps one in its source, in its own format) into
   js/game-changelogs.js, which the game select menu (index.html) uses for its per-game Changelog
   tabs. Run it after shipping an update to any game:

     node tools/build-changelogs.js

   Output shape: window.GAME_CHANGELOGS = { <id>: { nm, href, entries: [{v, d, items: [...]}] } } */
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..");

/* pull the array literal that follows `marker` out of a file, balancing brackets and skipping strings */
function extractArray(src, marker) {
  const at = src.indexOf(marker);
  if (at < 0) return null;
  let i = src.indexOf("[", at + marker.length - 1);
  const start = i;
  let depth = 0, q = null;
  for (; i < src.length; i++) {
    const ch = src[i];
    if (q) {
      if (ch === "\\") { i++; continue; }
      if (ch === q) q = null;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === "`") { q = ch; continue; }
    if (ch === "[") depth++;
    else if (ch === "]") { depth--; if (depth === 0) return src.slice(start, i + 1); }
  }
  return null;
}
function evalArray(lit) {
  // the literals are plain data (strings, numbers, objects, arrays) written by us in our own games
  return new Function("return " + lit)();
}
function read(f) { return fs.readFileSync(path.join(ROOT, f), "utf8"); }
function fmtDate(iso) {
  const d = new Date(iso);
  if (isNaN(d)) return iso;
  return d.toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric", timeZone: "America/New_York" });
}
const GAMES = [
  { id: "conquest", nm: "Space Conquest", href: "conquest.html", file: "conquest.html", marker: "var CHANGELOG=",
    map: (e) => ({ v: e.v, d: e.t, items: e.items }) },
  { id: "meatlad", nm: "Meat Lad", href: "meatlad.html", file: "meatlad.html", marker: "var CHANGELOG=",
    map: (e) => ({ v: e.v, d: e.d, items: e.items }) },
  { id: "pantry", nm: "Alien Attack", href: "pantry.html", file: "pantry.html", marker: "var CHANGELOG=",
    map: (e) => ({ v: e.v, d: e.d, items: e.items }) },
  { id: "beetdown", nm: "Beetdown", href: "beetdown.html", file: "beetdown.html", marker: "var CHANGELOG=",
    map: (e) => ({ v: e.v, d: e.d, items: e.items }) },
  { id: "linework", nm: "Linework", href: "linework.html", file: "linework.html", marker: "const CHANGELOG=",
    map: (e) => ({ v: e.v, d: e.t, items: e.items }) },
  { id: "quackpot", nm: "Quackpot", href: "quackpot.html", file: "quackpot.html", marker: "const CHANGELOG=",
    map: (e) => ({ v: fmtDate(e.date), d: e.title, items: e.notes }) },
  { id: "deepcore", nm: "Deepcore", href: "deepcore.html", file: "deepcore.html", marker: "const CHANGELOG=",
    map: (e) => ({ v: e.v, d: e.t, items: e.items }) },
  { id: "gridlock", nm: "Gridlock", href: "gridlock.html", file: "gridlock.html", marker: "const CHANGES=",
    map: (e) => ({ v: e[0], d: e[1], items: e[2] }) },
];
const out = {};
for (const g of GAMES) {
  const lit = extractArray(read(g.file), g.marker);
  if (!lit) { console.warn("no changelog found in " + g.file); continue; }
  const entries = evalArray(lit).map(g.map).filter((e) => e.items && e.items.length);
  out[g.id] = { nm: g.nm, href: g.href, entries };
  console.log(g.nm.padEnd(16) + entries.length + " entries");
}
/* Starforge (a separate bundled app) and Rise & Fall don't carry an in-game changelog; their
   history lives in the menu's own overall log, so pick their lines out of it */
const indexSrc = read("index.html");
const overallLit = extractArray(indexSrc, "var OVERALL_LOG=");
const overall = overallLit ? evalArray(overallLit) : [];
function fromOverall(prefixRe) {
  const entries = [];
  overall.forEach((day) => {
    const items = day.items.filter((it) => prefixRe.test(it));
    if (items.length) entries.push({ v: day.v, d: (day.d || "").replace(/^latest · /, ""), items });
  });
  return entries;
}
out.starforge = { nm: "Starforge", href: "starforge/", entries: fromOverall(/^STARFORGE/i) };
out.risefall = { nm: "Rise & Fall", href: "risefall.html", entries: fromOverall(/^RISE ?(&|AND) ?FALL/i) };
if (!out.risefall.entries.length) {
  out.risefall.entries = [{ v: "1.0", d: "Launch", items: [
    "A living history generator: pick a world from Small to Colossal and watch nations rise from a single camp — farming, trading, colonising distant continents, conquering, rebelling and winning independence.",
  ] }];
}
const js = "/* generated by tools/build-changelogs.js — do not edit by hand, re-run the tool instead */\n" +
  "window.GAME_CHANGELOGS=" + JSON.stringify(out) + ";\n";
fs.writeFileSync(path.join(ROOT, "js", "game-changelogs.js"), js);
console.log("wrote js/game-changelogs.js (" + Math.round(js.length / 1024) + " KB)");
